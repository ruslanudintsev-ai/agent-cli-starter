"""Build the CLI skill reference from real registered argparse subparsers."""

from __future__ import annotations

import argparse
from pathlib import Path
from collections.abc import Mapping
from typing import Any

from core.commands.base import BaseCommand


def cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").replace("`", "'")


def argument_rows(parser: argparse.ArgumentParser) -> list[str]:
    rows: list[str] = []
    for action in parser._actions:
        if isinstance(action, argparse._HelpAction):
            continue
        flags = ", ".join(action.option_strings) if action.option_strings else action.dest
        required = "yes" if action.required else "no"
        if isinstance(action, argparse._StoreTrueAction):
            value_type = "flag"
        elif action.choices:
            value_type = " / ".join(map(str, action.choices))
        elif action.type:
            value_type = getattr(action.type, "__name__", str(action.type))
        else:
            value_type = "str" if action.nargs != 0 else "flag"
        default = "—" if action.default is argparse.SUPPRESS else repr(action.default)
        rows.append(f"| `{cell(flags)}` | {cell(value_type)} | {required} | {cell(default)} | {cell(action.help or '')} |")
    return rows


class SystemDocgenCommand(BaseCommand):
    name = "system-docgen"
    description = "Regenerate the CLI command reference from registered argparse parsers"

    def configure_parser(self, parser: argparse.ArgumentParser) -> None:
        parser.add_argument("--output", default=".agents/skills/cli-tools/SKILL.md", help="Destination Markdown file")
        parser.add_argument("--dry-run", action="store_true", help="Validate generated docs without writing")

    def run(self, args: argparse.Namespace) -> Mapping[str, Any]:
        parsers: dict[str, argparse.ArgumentParser] = args._subparsers
        entry = args._entrypoint
        lines = [
            "---", "name: cli-tools", "description: CLI command reference, autogenerated from argparse", "---",
            "", "# CLI Tools", "", "Generated by `system-docgen`. Do not edit manually.", "",
            f"Entry point: `python {entry} <command> --json`", "",
            "## Commands", "",
        ]
        for name, parser in sorted(parsers.items()):
            lines.extend([
                f"### `{name}`", "", parser.description or "No description.", "",
                f"Usage: `python {entry} {name} --json`", "",
                "| Argument | Type | Required | Default | Description |",
                "| --- | --- | --- | --- | --- |", *argument_rows(parser), "",
            ])
        document = "\n".join(lines).rstrip() + "\n"
        output = Path(args.output)
        if not args.dry_run:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(document, encoding="utf-8")
        return {"status": "ok", "commands": len(parsers), "output": str(output),
                "dry_run": args.dry_run, "document_length": len(document)}
